-- CREATE EXTENSION은 슈퍼유저 권한을 요구한다. compose와 배포 환경 모두 POSTGRES_USER가
-- initdb로 생성된 슈퍼유저이고 Backend가 같은 계정으로 접속하므로 이 마이그레이션이 통과한다.
-- 애플리케이션 계정을 일반 사용자로 분리한다면 그 전에 확장을 미리 설치해 두어야 한다.
CREATE EXTENSION IF NOT EXISTS vector;

-- 보스 제출 유사 문장 차단(정책 §6.10)에 사용한다. 평가 완료 시점에 1행을 저장하고
-- 제출 시점에는 같은 사용자·같은 BossRun의 이전 제출 벡터와만 비교한다.
-- model_name은 비교 대상을 같은 모델로 제한하기 위해 저장한다. 모델이 바뀌면 벡터 공간이
-- 달라져 서로 다른 모델의 벡터 사이 거리는 의미가 없다.
CREATE TABLE sentence_embeddings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sentence_version_id BIGINT NOT NULL UNIQUE REFERENCES sentence_versions (id),
    embedding vector(768) NOT NULL,
    model_name VARCHAR(100) NOT NULL,
    -- 벡터 컬럼 타입이 이미 차원을 강제하므로 이 값은 스냅샷 기록용이다. CHECK가 없으면
    -- 애플리케이션이 잘못된 상수를 넣어도 DB가 막지 못해 기록으로서의 신뢰성이 사라진다.
    -- 차원을 바꾸려면 vector(N)과 이 제약을 함께 변경해야 한다.
    dimension INTEGER NOT NULL CHECK (dimension = 768),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

-- 벡터 인덱스(HNSW/IVFFlat)는 만들지 않는다. 비교 범위가 사용자·회차당 최대 수십 건이라
-- 순차 스캔이 더 빠르고, 인덱스는 쓰기 비용과 근사 오차만 추가한다.
