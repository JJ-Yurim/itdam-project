CREATE TABLE image_assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    storage_key VARCHAR(500) NOT NULL UNIQUE,
    content_type VARCHAR(100) NOT NULL,
    byte_size BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL,
    created_by BIGINT NOT NULL REFERENCES users (id),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_image_assets_status_created_at ON image_assets (status, created_at);

CREATE TABLE boss_phase_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    boss_id BIGINT NOT NULL REFERENCES bosses (id),
    phase_no INTEGER NOT NULL,
    max_hp BIGINT NOT NULL,
    hard_min_score NUMERIC(6, 2),
    recommended_score NUMERIC(6, 2),
    damage_multiplier NUMERIC(6, 3) NOT NULL,
    image_asset_id BIGINT NOT NULL REFERENCES image_assets (id),
    CONSTRAINT uk_boss_phase_templates_boss_phase UNIQUE (boss_id, phase_no)
);

ALTER TABLE boss_phases
    ADD COLUMN image_asset_id BIGINT REFERENCES image_assets (id);
