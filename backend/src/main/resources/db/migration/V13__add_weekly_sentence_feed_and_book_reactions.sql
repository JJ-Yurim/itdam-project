CREATE TABLE book_likes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id),
    book_id BIGINT NOT NULL REFERENCES books (id),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_book_like_user_book UNIQUE (user_id, book_id)
);

CREATE INDEX idx_book_likes_book ON book_likes (book_id);

CREATE TABLE book_bookmarks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id),
    book_id BIGINT NOT NULL REFERENCES books (id),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_book_bookmark_user_book UNIQUE (user_id, book_id)
);

CREATE INDEX idx_book_bookmarks_book ON book_bookmarks (book_id);
