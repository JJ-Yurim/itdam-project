CREATE TABLE weekly_sentence_sets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    week_start_date DATE NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_weekly_sentence_set_week UNIQUE (week_start_date)
);

CREATE TABLE weekly_sentence_set_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    weekly_sentence_set_id BIGINT NOT NULL REFERENCES weekly_sentence_sets (id),
    book_content_id BIGINT NOT NULL REFERENCES book_contents (id),
    position INTEGER NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_weekly_sentence_item_set_position UNIQUE (weekly_sentence_set_id, position),
    CONSTRAINT uk_weekly_sentence_item_set_content UNIQUE (weekly_sentence_set_id, book_content_id)
);

CREATE TABLE book_content_likes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id),
    book_content_id BIGINT NOT NULL REFERENCES book_contents (id),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_book_content_like_user_content UNIQUE (user_id, book_content_id)
);

CREATE INDEX idx_book_content_likes_content ON book_content_likes (book_content_id);

