CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    nickname VARCHAR(100) NOT NULL UNIQUE,
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE words (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word VARCHAR(100) NOT NULL,
    part_of_speech VARCHAR(50) NOT NULL,
    definition TEXT NOT NULL,
    example TEXT,
    is_active BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_words_active_id ON words (is_active, id);

CREATE TABLE daily_word_sets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id),
    service_date DATE NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_daily_word_set_user_date UNIQUE (user_id, service_date)
);

CREATE TABLE daily_word_set_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    daily_word_set_id BIGINT NOT NULL REFERENCES daily_word_sets (id),
    word_id BIGINT NOT NULL REFERENCES words (id),
    position SMALLINT NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_daily_word_item_set_position UNIQUE (daily_word_set_id, position),
    CONSTRAINT uk_daily_word_item_set_word UNIQUE (daily_word_set_id, word_id)
);

CREATE TABLE sentences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id),
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    deleted_at TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE sentence_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sentence_id BIGINT NOT NULL REFERENCES sentences (id),
    version_no INTEGER NOT NULL,
    content TEXT NOT NULL,
    evaluation_status VARCHAR(30) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    confirmed_at TIMESTAMP(6) WITH TIME ZONE,
    evaluation_started_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_sentence_version_no UNIQUE (sentence_id, version_no)
);
CREATE INDEX idx_sentence_version_status ON sentence_versions (evaluation_status);

CREATE TABLE mood_categories (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE,
    name_ko VARCHAR(50) NOT NULL,
    is_active BOOLEAN NOT NULL
);

CREATE TABLE sentence_evaluations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sentence_version_id BIGINT NOT NULL UNIQUE REFERENCES sentence_versions (id),
    safety_status VARCHAR(30) NOT NULL,
    safety_reason TEXT,
    completeness_score INTEGER,
    originality_score INTEGER,
    expression_score INTEGER,
    imagery_score INTEGER,
    emotional_impact_score INTEGER,
    base_score NUMERIC(6, 2),
    word_bonus NUMERIC(6, 2) NOT NULL,
    game_base_attack NUMERIC(6, 2) NOT NULL,
    overall_feedback TEXT,
    model_name VARCHAR(100),
    prompt_version VARCHAR(50),
    rubric_version VARCHAR(50),
    evaluated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE sentence_moods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sentence_version_id BIGINT NOT NULL REFERENCES sentence_versions (id),
    mood_category_id SMALLINT NOT NULL REFERENCES mood_categories (id),
    strength NUMERIC(4, 3) NOT NULL,
    rank SMALLINT NOT NULL,
    CONSTRAINT uk_sentence_mood_category UNIQUE (sentence_version_id, mood_category_id),
    CONSTRAINT uk_sentence_mood_rank UNIQUE (sentence_version_id, rank)
);

CREATE TABLE sentence_used_daily_words (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sentence_version_id BIGINT NOT NULL REFERENCES sentence_versions (id),
    daily_word_set_item_id BIGINT NOT NULL REFERENCES daily_word_set_items (id),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_sentence_used_daily_word UNIQUE (sentence_version_id, daily_word_set_item_id)
);

CREATE TABLE user_daily_evaluation_usage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id),
    service_date DATE NOT NULL,
    used_count INTEGER NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_user_daily_evaluation_usage UNIQUE (user_id, service_date)
);

CREATE TABLE bosses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description TEXT NOT NULL,
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE boss_moods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    boss_id BIGINT NOT NULL REFERENCES bosses (id),
    mood_category_id SMALLINT NOT NULL REFERENCES mood_categories (id),
    mood_role VARCHAR(30) NOT NULL,
    weight NUMERIC(6, 3) NOT NULL,
    CONSTRAINT uk_boss_mood_category_role UNIQUE (boss_id, mood_category_id, mood_role)
);

CREATE TABLE boss_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    boss_id BIGINT NOT NULL REFERENCES bosses (id),
    status VARCHAR(30) NOT NULL,
    current_phase_no INTEGER NOT NULL,
    accumulated_damage BIGINT NOT NULL,
    started_at TIMESTAMP(6) WITH TIME ZONE,
    ends_at TIMESTAMP(6) WITH TIME ZONE,
    cleared_at TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_boss_runs_status_ends_at ON boss_runs (status, ends_at);

CREATE TABLE boss_phases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    boss_run_id BIGINT NOT NULL REFERENCES boss_runs (id),
    phase_no INTEGER NOT NULL,
    max_hp BIGINT NOT NULL,
    remaining_hp BIGINT NOT NULL,
    hard_min_score NUMERIC(6, 2),
    recommended_score NUMERIC(6, 2),
    damage_multiplier NUMERIC(6, 3) NOT NULL,
    status VARCHAR(30) NOT NULL,
    CONSTRAINT uk_boss_run_phase_no UNIQUE (boss_run_id, phase_no)
);

CREATE TABLE boss_submission_daily_counters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    boss_run_id BIGINT NOT NULL REFERENCES boss_runs (id),
    user_id BIGINT NOT NULL REFERENCES users (id),
    service_date DATE NOT NULL,
    submission_count INTEGER NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_boss_submission_counter_run_user_date UNIQUE (boss_run_id, user_id, service_date)
);

CREATE TABLE boss_submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    boss_run_id BIGINT NOT NULL REFERENCES boss_runs (id),
    boss_phase_id BIGINT NOT NULL REFERENCES boss_phases (id),
    user_id BIGINT NOT NULL REFERENCES users (id),
    sentence_version_id BIGINT NOT NULL REFERENCES sentence_versions (id),
    service_date DATE NOT NULL,
    ai_base_score_snapshot NUMERIC(6, 2) NOT NULL,
    word_bonus_snapshot NUMERIC(6, 2) NOT NULL,
    mood_bonus_snapshot NUMERIC(6, 2) NOT NULL,
    weakness_bonus_snapshot NUMERIC(6, 2) NOT NULL,
    phase_modifier_snapshot NUMERIC(6, 3) NOT NULL,
    final_damage BIGINT NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_boss_submission_run_version UNIQUE (boss_run_id, sentence_version_id)
);
CREATE INDEX idx_boss_submission_run_user_date ON boss_submissions (boss_run_id, user_id, service_date);
CREATE INDEX idx_boss_submission_phase ON boss_submissions (boss_phase_id);

CREATE TABLE books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    boss_run_id BIGINT NOT NULL UNIQUE REFERENCES boss_runs (id),
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE ai_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    boss_run_id BIGINT NOT NULL REFERENCES boss_runs (id),
    job_type VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL,
    attempt_count INTEGER NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    requested_at TIMESTAMP(6) WITH TIME ZONE,
    request_dispatched BOOLEAN NOT NULL,
    last_error VARCHAR(500),
    CONSTRAINT uk_ai_jobs_run_type UNIQUE (boss_run_id, job_type)
);
CREATE INDEX idx_ai_jobs_status ON ai_jobs (status);

CREATE TABLE book_contents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id BIGINT NOT NULL REFERENCES books (id),
    sequence_no INTEGER NOT NULL,
    content_type VARCHAR(20) NOT NULL,
    content VARCHAR(10000) NOT NULL,
    author_user_id BIGINT REFERENCES users (id),
    source_submission_id BIGINT REFERENCES boss_submissions (id),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_book_contents_book_sequence UNIQUE (book_id, sequence_no)
);
